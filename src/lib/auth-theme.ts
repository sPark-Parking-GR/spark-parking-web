export function authThemeVars(mode: 'dark' | 'light'): string {
  const palette: Record<string, string> = mode === 'dark' ? DARK : LIGHT
  return Object.entries(palette)
    .map(([name, value]) => `--auth-${name}:${value};`)
    .join('')
}
